-- Миграция 3: согласие пользователя по категориям разрешений (ТЗ §21).
--
-- Включены по умолчанию те категории, без которых десктопный ассистент не
-- ассистент, и которые сами по себе не дают ничего сверх того, на что человек
-- согласился, устанавливая приложение: файлы, сеть, уведомления, браузер.
-- Опасность внутри этих категорий гасится не запретом целиком, а уровнем риска
-- из ТЗ §22 — удаление файла всё равно потребует подтверждения.
--
-- Выключены те, что дают качественно новый доступ: shell, ввод и чтение экрана,
-- микрофон, камера и передача данных наружу. Их включает человек осознанно.
--
-- Это временное умолчание: по-хорошему согласие собирает мастер первого запуска
-- (docs/GAPS.md §1), и тогда эта миграция станет его начальным состоянием.

UPDATE permissions SET granted = 1, updated_at = unixepoch()
WHERE category IN ('files', 'network', 'notifications', 'browser');
