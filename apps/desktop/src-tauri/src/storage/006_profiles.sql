-- Профили персонажа (ТЗ §11, docs/GAPS.md §7).
--
-- Модель, анимации, характер, обращение и слово пробуждения — это не пять
-- независимых настроек, а один облик. Менять их по одной означает, что смена
-- персонажа складывается из пяти походов в разные части настроек, и половина
-- из них забывается.
--
-- Профиль хранит снимок настроек целиком, а не ссылки на них: иначе профиль,
-- сделанный полгода назад, ломался бы от появления новой настройки, а старая,
-- убранная из списка, тихо оставалась бы от прежнего персонажа.
CREATE TABLE IF NOT EXISTS profiles (
    id         TEXT PRIMARY KEY,
    name       TEXT NOT NULL,
    -- JSON-объект «ключ настройки → значение». Текстом, потому что состав
    -- ключей меняется вместе с приложением, а колонки под каждую настройку
    -- требовали бы миграции на каждое новое свойство персонажа.
    data       TEXT NOT NULL,
    created_at INTEGER NOT NULL DEFAULT (unixepoch()),
    updated_at INTEGER NOT NULL DEFAULT (unixepoch())
);

-- Имя ассистента: его видно в интерфейсе вместо «Yuki», и оно же часть облика.
-- Пустое значение означает «как в поставке» — подставлять сюда «Yuki» нельзя,
-- иначе переименование приложения в будущем прошло бы мимо тех, кто ничего не
-- менял.
INSERT INTO settings (key, value) VALUES ('persona.name', '')
    ON CONFLICT(key) DO NOTHING;
