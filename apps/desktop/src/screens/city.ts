/**
 * Город, в котором стоит компьютер.
 *
 * Заданный в настройках город всегда важнее. Но пока его нет, виджет погоды
 * не показывался вовсе, и человеку приходилось искать настройку, о которой он
 * не знал. Часовой пояс машины — это единственный источник места, который уже
 * лежит на самом компьютере: `Europe/Moscow` не требует ни спутника, ни
 * поиска по адресу, ни отправки чего-либо наружу.
 *
 * Догадка приблизительна, и это надо называть своим именем: `Europe/Kiev`
 * покрывает всю страну, `America/New_York` — четверть материка. Поэтому
 * найденное название показывается как есть, а настройка его перекрывает.
 */

/**
 * Достаёт название города из имени часового пояса IANA.
 *
 * `null` означает «по этому имени города не узнать» — так бывает у `UTC`,
 * у смещений вида `Etc/GMT+3` и у сокращений вроде `MSK`. Возвращать в этом
 * случае что-нибудь наугад хуже, чем не возвращать ничего: поиск погоды по
 * «GMT+3» найдёт неизвестно что и покажет это как место, где человек живёт.
 */
export function cityFromTimeZone(zone: string | null | undefined): string | null {
  if (!zone) return null

  const parts = zone.split('/')

  // Однословные имена — это не места: `UTC`, `MSK`, `localtime`.
  if (parts.length < 2) return null

  // `Etc/*` — это смещения, а не города.
  if (parts[0] === 'Etc') return null

  // Последний отрезок, потому что бывают трёхуровневые имена вида
  // `America/Argentina/Buenos_Aires`, и город в них последний.
  const last = parts[parts.length - 1] ?? ''

  // Только буквы, подчёркивания и дефисы: всё остальное — смещение или мусор.
  if (!/^[A-Za-z][A-Za-z_-]*$/.test(last)) return null

  return last.replace(/_/g, ' ')
}

/** Часовой пояс самой машины — отдельной функцией, чтобы его можно было подменить в тесте. */
export function localTimeZone(): string | null {
  try {
    return Intl.DateTimeFormat().resolvedOptions().timeZone ?? null
  } catch {
    return null
  }
}
